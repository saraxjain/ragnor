// Output guardrail: every Gemini / agent string shown to a user passes through sanitize().
// Ragnor never diagnoses and never clears an athlete. Any sentence that does is replaced.

export const SAFE_REPLACEMENT =
  "Ragnor can't make that call. Talk to your coach, athletic trainer or a clinician.";

// Patterns that must never reach a user in model-generated text.
export const BANNED_PATTERNS: { id: string; re: RegExp }[] = [
  { id: "diagnosis", re: /\bdiagnos(e|es|ed|is|ing|tic)\b/i },
  { id: "cleared", re: /\b(cleared|clearance|clear to (play|return|practice))\b/i },
  { id: "safe_to_play", re: /\bsafe to (play|return|practice|compete)\b/i },
  { id: "youre_fine", re: /\b(you('| a)re|you're) (fine|okay|ok|good to go|all good|healthy)\b/i },
  { id: "good_to_go", re: /\bgood to go\b/i },
  { id: "no_concussion", re: /\b(no|not a|don't have a|do not have a) concussion\b/i },
  { id: "has_concussion", re: /\b(you|they|he|she) (have|has|had) a concussion\b/i },
  { id: "return_to_play_ok", re: /\b(ready|able|can) (to )?return to (play|practice|sport)\b/i },
  { id: "prevents_injury", re: /\b(prevents?|guarantees?) (all )?(injur(y|ies)|concussions?|acl)\b/i },
];

export interface SanitizeResult {
  text: string;
  blocked: string[]; // ids of patterns that fired
  changed: boolean;
}

function splitSentences(text: string): string[] {
  // Keeps the punctuation with each sentence.
  return text.match(/[^.!?\n]+[.!?]*\s*|\n+/g) ?? [text];
}

export function findViolations(text: string): string[] {
  return BANNED_PATTERNS.filter((p) => p.re.test(text)).map((p) => p.id);
}

/** Replace every sentence that contains a banned pattern with SAFE_REPLACEMENT (once). */
export function sanitize(text: string): SanitizeResult {
  if (!text) return { text, blocked: [], changed: false };
  const blocked = new Set<string>();
  let replacedOnce = false;
  const out: string[] = [];
  for (const s of splitSentences(text)) {
    const hits = findViolations(s);
    if (hits.length === 0) {
      out.push(s);
      continue;
    }
    hits.forEach((h) => blocked.add(h));
    if (!replacedOnce) {
      out.push(SAFE_REPLACEMENT + (s.endsWith(" ") ? " " : ""));
      replacedOnce = true;
    }
  }
  const result = out.join("").replace(/\s{2,}/g, " ").trim();
  return { text: result, blocked: [...blocked], changed: blocked.size > 0 };
}

/** Deep-sanitize every string in a JSON value (e.g. a Gemini structured response). */
export function sanitizeDeep<T>(value: T, blockedOut: string[] = []): T {
  if (typeof value === "string") {
    const r = sanitize(value);
    blockedOut.push(...r.blocked);
    return r.text as unknown as T;
  }
  if (Array.isArray(value)) return value.map((v) => sanitizeDeep(v, blockedOut)) as unknown as T;
  if (value && typeof value === "object") {
    const o: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) o[k] = sanitizeDeep(v, blockedOut);
    return o as T;
  }
  return value;
}

/** Fixed message for any red-flag answer. Shown immediately, never generated by a model. */
export const RED_FLAG_MESSAGE =
  "That's important. Tell a parent or adult right now and get medical care. If it feels like an emergency, call 911.";
